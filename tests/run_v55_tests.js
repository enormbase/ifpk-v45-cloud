'use strict';
const assert=require('assert');
const E=require('../docs/js/v55_savings_engine.js');
const snap=require('../docs/data/v55_monthly_savings_snapshot.json');
const approximate=(a,b,tol=4)=>assert.ok(Math.abs(a-b)<tol, `${a} != ${b} (±${tol})`);
const s=E.simulate(snap);
assert.strictEqual(s.months.length,353);
assert.strictEqual(s.first.month,'2026-11');
approximate(s.first.available,898086.33333);
approximate(s.first.required.home,427725.7447);
approximate(s.first.required.car,189846.5609);
approximate(s.first.required.travel,112373.9582);
approximate(s.first.required.ret,245241.7628);
approximate(s.first.allocated.ret,168140.0695);
assert.strictEqual(s.book.car.shortfall,0);
approximate(s.book.travel.shortfall,0);
approximate(s.book.home.shortfall,1167618.4);
approximate(s.book.ret.shortfall,6823037.3);
assert.strictEqual(s.retirement.firstUnmet,'2082-09');
assert.ok(s.retirement.totalUnmet>1);
for(const r of s.months){
 assert.ok(r.assigned>=-0.01,`negative allocation ${r.month}`);
 assert.ok(r.assigned<Math.max(0,r.available)+1,`budget exceeded ${r.month}`);
}
const paid=E.simulate(snap,{actuals:{'2026-11':{ret:100000}}});
assert.strictEqual(paid.first.allocated.ret,100000);
assert.ok(paid.months[1].required.ret>s.months[1].required.ret);
assert.ok(paid.book.ret.shortfall>s.book.ret.shortfall);
const paidZero=E.simulate(snap,{actuals:{'2026-11':{ret:0}}});
assert.strictEqual(paidZero.first.allocated.ret,0);
assert.strictEqual(paidZero.actualCount.ret,1);
assert.strictEqual(s.actualCount.ret,0);
const squeezed=E.simulate(snap,{cashOverrides:{'2026-11':{income:3000000,expense:2800000}}});
approximate(squeezed.first.allocated.home,200000);
assert.strictEqual(squeezed.first.allocated.car,0);
assert.ok(squeezed.months[1].required.home>s.months[1].required.home);
const econ=E.simulate(snap,{economics:{CPI_TRAVEL:{value:130,lastMonth:'2026-10',ready:true},DEPOSIT:{value:3.1,lastMonth:'2026-10',ready:true}},asOf:'2026-11'});
assert.ok(econ.byId.travel.total>s.byId.travel.total);
assert.ok(econ.byId.home.monthlyRate>s.byId.home.monthlyRate);
assert.strictEqual(econ.economics.changes.length,2);
const unapproved=E.simulate(snap,{economics:{CPI_TRAVEL:{value:130,lastMonth:'2026-10',ready:false}},asOf:'2026-11'});
assert.strictEqual(unapproved.byId.travel.total,s.byId.travel.total);
assert.throws(()=>E.simulate(snap,{priority:{ret:1,home:1}}),/우선순위/);
console.log('V55 PASS: 353 months, source parity, priority cap, rolling, actual 0, source data, retirement exhaustion');
