'use strict';
const assert=require('assert');
const E=require('../docs/js/v55_savings_engine.js'),M=require('../docs/js/v57_monthly_close.js'),snap=require('../docs/data/v55_monthly_savings_snapshot.json');
const goals=E.simulate(snap).goals,base=E.simulate(snap);
assert.strictEqual(goals.length,4);
assert.deepStrictEqual(goals.slice().sort((a,b)=>a.priority-b.priority).map(g=>g.id),['home','car','travel','ret']);
assert.strictEqual(M.nextMonth('2026-12'),'2027-01');
assert.strictEqual(M.nextMonth('2026-11'),'2026-12');
assert(M.validAmount('0'));assert(M.validAmount('500000'));assert(!M.validAmount(''));assert(!M.validAmount('-10'));assert(!M.validAmount('1.5'));
let state=M.blank();state.pending={home:'500000',car:'100000',travel:'0',ret:'400000'};
state.checks={home:true,car:true,travel:true,ret:false};
assert.strictEqual(M.pendingReady(state,goals,'2026-11'),false);
assert.throws(()=>M.closeMonth(state,goals,'2026-11'),/모든/);
state.checks.ret=true;
assert.strictEqual(M.pendingReady(state,goals,'2026-11'),true);
let res=M.closeMonth(state,goals,'2026-11',{required:base.first.required});
assert.strictEqual(res.state.active,'2026-12');
assert.strictEqual(res.actuals.travel,0);
assert.strictEqual(res.state.history['2026-11'].actuals.home,500000);
let s=E.simulate(snap,{actuals:{'2026-11':res.actuals}}),next='2026-12';
assert(s.byMonth[next].required.home < base.byMonth[next].required.home, 'extra home saving reduces next requirement');
assert(s.byMonth[next].required.car > base.byMonth[next].required.car, 'underpay car increases next requirement');
assert(s.byMonth[next].required.travel > base.byMonth[next].required.travel, 'zero travel increases next requirement');
assert(s.byMonth[next].required.ret < base.byMonth[next].required.ret, 'extra retirement saving reduces next requirement');
assert(s.first.free<0,'actual total higher than capacity retained as negative cash');
let restored=M.clean(JSON.parse(JSON.stringify(res.state)));
assert.strictEqual(restored.active,'2026-12');assert.strictEqual(restored.history['2026-11'].actuals.travel,0);
let opened=M.reopenLast(restored);assert.strictEqual(opened.state.active,'2026-11');assert.strictEqual(opened.state.pending.travel,'0');assert.strictEqual(opened.state.checks.travel,false);
assert.strictEqual(M.dueGoals(goals,'2040-01').includes('travel'),false);
assert.strictEqual(M.dueGoals(goals,'2050-01').includes('home'),false);
console.log('V57 PASS: four checks synchronized, manual 0, under/overpay rolling, goal closure, restore/reopen');
